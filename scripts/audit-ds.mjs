// Static check of the Stories (and the Developer docs that show them) against the design system.
// Counts, per file: legacy `T.*` colour primitives, hex / rgba literals, and numeric font sizes,
// radii and spacing that are not on the design system's scales. Writes JSON to the path given.
//   node scripts/audit-ds.mjs scripts/ds-audit-baseline.json
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { DS } from "../src/lib/dsTokens.generated.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dirs = ["src/components/scope/stories", "src/components/developer"];
const FONT = new Set(DS.type.map((t) => t.size));
const RADIUS = new Set(Object.values(DS.radius).concat([50]));          // "50%" circles are written as "50%", not a number
const SPACE = new Set(Object.values(DS.spacing));

const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => e.isDirectory() ? walk(path.join(d, e.name)) : /\.(jsx?|js)$/.test(e.name) ? [path.join(d, e.name)] : []);
const stripComments = (s) => s.replace(/\/\*[\s\S]*?\*\//g, "").replace(/(^|[^:])\/\/.*$/gm, "$1");

const out = { files: {}, totals: {} };
for (const dir of dirs) for (const f of walk(path.join(root, dir))) {
  const rel = path.relative(root, f);
  if (/dsAudit|AuditDoc/.test(rel)) continue;
  const src = stripComments(fs.readFileSync(f, "utf8"));
  const count = (re) => (src.match(re) || []).length;
  const nums = (re, pick) => [...src.matchAll(re)].flatMap((m) => pick(m)).filter((n) => Number.isFinite(n));
  const fonts = nums(/fontSize:\s*(\d+(?:\.\d+)?)/g, (m) => [parseFloat(m[1])]);
  const radii = nums(/[rR]adius:\s*(\d+(?:\.\d+)?)\b/g, (m) => [parseFloat(m[1])]);
  const space = nums(/\b(?:gap|rowGap|columnGap|padding\w*|margin\w*)\s*:\s*(?:"([^"]*)"|(-?\d+(?:\.\d+)?))/g, (m) => (m[1] ? m[1].match(/-?\d+(?:\.\d+)?/g) || [] : [m[2]]).map(parseFloat)).filter((n) => n !== 0);
  out.files[rel] = {
    tPrimitives: count(/\bT\.[A-Za-z0-9]+/g),
    hex: count(/#[0-9a-fA-F]{3,8}\b/g),
    rgba: count(/rgba?\(/g),
    offScaleFont: [...new Set(fonts.filter((n) => !FONT.has(n)))].sort((a, b) => a - b),
    offScaleRadius: [...new Set(radii.filter((n) => !RADIUS.has(n)))].sort((a, b) => a - b),
    offScaleSpace: [...new Set(space.filter((n) => !SPACE.has(Math.abs(n))))].sort((a, b) => a - b),
    dsTokens: count(/\bds(?:\.[A-Za-z0-9]+)+|\bdsBand\(|\bdsShadow\(|\bdsRadius\b|\bdsText\(/g),
  };
}
const files = Object.values(out.files);
const sum = (k) => files.reduce((a, f) => a + f[k], 0);
out.totals = { files: files.length, tPrimitives: sum("tPrimitives"), hex: sum("hex"), rgba: sum("rgba"), offScaleFont: files.reduce((a, f) => a + f.offScaleFont.length, 0), offScaleRadius: files.reduce((a, f) => a + f.offScaleRadius.length, 0), offScaleSpace: files.reduce((a, f) => a + f.offScaleSpace.length, 0), dsTokens: sum("dsTokens") };
fs.writeFileSync(path.resolve(root, process.argv[2] || "scripts/ds-audit.json"), JSON.stringify(out, null, 1));
// With a baseline on disk, also publish {baseline, current} for the Developer "Token audit" page.
const baselinePath = path.resolve(root, "scripts/ds-audit-baseline.json");
if (process.argv[2] !== "scripts/ds-audit-baseline.json" && fs.existsSync(baselinePath)) {
  const baseline = JSON.parse(fs.readFileSync(baselinePath, "utf8"));
  fs.writeFileSync(path.resolve(root, "src/lib/dsAudit.generated.js"), `/* GENERATED by scripts/audit-ds.mjs - do not edit by hand. */\nexport const AUDIT = ${JSON.stringify({ baseline, current: out }, null, 1)};\n`);
}
console.log(out.totals);
for (const [f, r] of Object.entries(out.files)) if (r.tPrimitives || r.hex || r.rgba) console.log(String(r.tPrimitives).padStart(4), String(r.hex).padStart(3), String(r.rgba).padStart(3), r.offScaleFont.join(",") || "-", "|", r.offScaleRadius.join(",") || "-", "|", r.offScaleSpace.join(",") || "-", " ", f.replace("src/components/", ""));
