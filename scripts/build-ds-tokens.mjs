// Reads docs/shape-design-system-v4.md (the design system's own reference) and writes
// src/lib/dsTokens.generated.js — every semantic token with its light and dark value, the
// primitives, shadows, radius, spacing, border widths and the type scale. The markdown is the
// source of truth: edit it, run `node scripts/build-ds-tokens.mjs`, commit both.
import fs from "node:fs";
const md = fs.readFileSync(new URL("../docs/shape-design-system-v4.md", import.meta.url), "utf8").split("\n");
const strip = (s) => s.trim().replace(/^`|`$/g, "");
const cells = (line) => line.split("|").slice(1, -1).map((c) => c.trim());

const out = { semantic: {}, primitives: {}, shadows: {}, radius: {}, spacing: {}, borderWidth: {}, opacity: {}, breakpoints: {}, type: [] };
let section = "", shadow = null;
for (const line of md) {
  const h = line.match(/^#{2,4} (.*)$/);
  if (h) {
    section = h[1];
    const sh = section.match(/`Shadow\/shadow-(\w+)`/);
    shadow = sh ? sh[1] : null;
    continue;
  }
  if (!line.startsWith("|")) continue;
  const c = cells(line);
  if (c.every((x) => /^[-:\s]*$/.test(x))) continue; // separator row
  const first = strip(c[0] || "");

  const colorish = (v) => /^(#|rgba?\()/.test(strip(v || ""));
  if (/^Type Scale/.test(section)) {
    if (/^(Display|Text|Label)/.test(first)) out.type.push({ name: first, size: parseInt(c[1], 10), lineHeight: c[2], tracking: c[3], note: c[4] || "" });
    continue;
  }
  if (shadow && /^\d$/.test(first)) { // | 1 | 0, 14px | 4px | `var` | `#..` | `#..` |
    (out.shadows[shadow] ||= []).push({ y: parseInt(c[1].split(",")[1], 10), blur: parseInt(c[2], 10), variable: strip(c[3]), light: strip(c[4]), dark: strip(c[5]) });
    continue;
  }
  if (/^Colors\//.test(first)) { out.primitives[first] = strip(c[1]); continue; }
  if (/^(color|utility)\//.test(first) && c.length >= 3 && colorish(c[1])) {
    if (/^color\/opacity\//.test(first)) { out.semantic[first] = { light: strip(c[1]), dark: strip(c[1]) }; continue; }
    out.semantic[first] = { light: strip(c[1]), dark: strip(c[2]) };
    continue;
  }
  // graph colours: | Name | `utility/Graph Colors/Main/X` | `#hex` |
  const g = strip(c[1] || "");
  if (/^utility\/Graph Colors\//.test(g) && colorish(c[2])) { out.semantic[g] = { light: strip(c[2]), dark: strip(c[2]) }; continue; }
  if (/^radius\//.test(first)) { out.radius[first] = parseInt(c[1], 10); continue; }
  if (/^border-width\//.test(first)) { out.borderWidth[first] = parseInt(c[1], 10); continue; }
  if (/^breakpoint\//.test(first)) { out.breakpoints[first] = parseInt(c[1], 10); continue; }
  if (/^spacing\//.test(first) || /^spacing\//.test(strip(c[2] || ""))) {
    if (/^spacing\//.test(first)) out.spacing[first] = parseInt(c[1], 10);
    if (/^spacing\//.test(strip(c[2] || ""))) out.spacing[strip(c[2])] = parseInt(c[3], 10);
    continue;
  }
  if (/^opacity\//.test(first)) { out.opacity[first] = parseFloat(c[1]); if (/^opacity\//.test(strip(c[2] || ""))) out.opacity[strip(c[2])] = parseFloat(c[3]); continue; }
}
const n = (o) => Object.keys(o).length;
fs.writeFileSync(
  new URL("../src/lib/dsTokens.generated.js", import.meta.url),
  `/* GENERATED by scripts/build-ds-tokens.mjs from docs/shape-design-system-v4.md — do not edit by hand. */\nexport const DS = ${JSON.stringify(out, null, 1)};\n`
);
console.log(`semantic ${n(out.semantic)} · primitives ${n(out.primitives)} · shadows ${n(out.shadows)} · radius ${n(out.radius)} · spacing ${n(out.spacing)} · borderWidth ${n(out.borderWidth)} · opacity ${n(out.opacity)} · type ${out.type.length}`);
